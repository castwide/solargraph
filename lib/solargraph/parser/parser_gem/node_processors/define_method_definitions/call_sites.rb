# frozen_string_literal: true

module Solargraph
  module Parser
    module ParserGem
      module NodeProcessors
        module DefineMethodDefinitions
          # Maps the methods that templates define, at each call made at class
          # level to a method that carries them, e.g., +add_flash_types :alert+.
          class CallSites
            # @param api_map [ApiMap]
            def initialize api_map
              @api_map = api_map
            end

            # @return [Array<Pin::Method>]
            def pins
              template_pins = api_map.call_site_template_pins.transform_values do |pins|
                pins.select { |pin| pin.call_site_templates.any?(Template) }
              end
              template_pins.reject! { |_name, pins| pins.empty? }
              return [] if template_pins.empty?
              api_map.source_maps.flat_map { |map| call_pins(map, template_pins) }
            end

            private

            # @return [ApiMap]
            attr_reader :api_map

            # The methods generated by calls at class level to methods with
            # templates in a source, e.g., +add_flash_types :alert+.
            #
            # @param source_map [SourceMap]
            # @param template_pins [Hash{String => Array<Pin::Method>}]
            # @return [Array<Pin::Method>]
            def call_pins source_map, template_pins
              source_map.method_call_nodes.flat_map do |node|
                # s(:send, receiver, method_name, *args), called on self
                next [] unless node in [:send, nil | [:self], Symbol => method_name, *]
                # @sg-ignore https://github.com/castwide/solargraph/pull/1416
                candidates = template_pins[method_name.to_s]
                next [] unless candidates
                namespace = class_level_namespace(source_map.locate_closure_pin(node.location.line, node.location.column))
                next [] unless namespace
                match = candidates.find { |pin| callable_from?(pin, namespace) }
                next [] unless match
                range = Range.from_node(node)
                next [] unless range
                location = Location.new(source_map.filename, range)
                # @type [Array<Template>]
                templates = match.call_site_templates.grep(Template).uniq(&:key)
                # @type [Array<Pin::Method>]
                pins = templates.flat_map { |template| template.generate_pins(node, namespace, location) }
                pins.uniq { |pin| [pin.scope, pin.name] }
              end
            end

            # The namespace whose body a closure belongs to, or nil if the closure
            # is in a method, where self is not the namespace.
            #
            # @param closure [Pin::Closure, nil]
            # @return [Pin::Namespace, nil]
            def class_level_namespace closure
              closure = closure.closure while closure.is_a?(Pin::Block)
              closure if closure.is_a?(Pin::Namespace)
            end

            # True if a call to the method's name in the namespace's body calls
            # the method. Besides the namespace's own class methods, this
            # accepts methods in modules nested in the namespace, e.g., an
            # ActiveSupport::Concern's ClassMethods called from its +included+
            # block.
            #
            # @param pin [Pin::Method]
            # @param namespace [Pin::Namespace]
            def callable_from? pin, namespace
              pin.namespace.start_with?("#{namespace.path}::") ||
                api_map.get_complex_type_methods(namespace.return_type).include?(pin)
            end
          end
        end
      end
    end
  end
end
